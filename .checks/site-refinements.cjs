  assert.equal(next.pages.home.sections.hero.image,'/assets/img/jimmy-park-portrait-960.jpg');
  assert.match(next.pages.lecture.sections.talks.items.find(row=>row.category==='Publication').title,/^인플루언서.*\(Influencer,/);
